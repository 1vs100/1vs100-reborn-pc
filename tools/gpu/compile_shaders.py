"""Compile the renderer's host shaders into embedded DXIL, DXBC and SPIR-V headers.

usage: python3 tools/gpu/compile_shaders.py [--dxc PATH] [--vkd3d PATH]
Each native/src/render/shaders/<name>.hlsl becomes native/src/render/shaders/<name>_shaders.h.
The default DXC is the Linux build that native/CMakeLists.txt fetches. DXBC (shader model 5.1, for D3D12
devices without shader model 6) comes from vkd3d-shader's compiler: the mingw build runs under Wine.
"""
import argparse
import os
import subprocess
import sys
import tempfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SHADERS = os.path.join(ROOT, 'native', 'src', 'render', 'shaders')
DXC_BIN = os.path.join(ROOT, 'native', 'third_party', 'xenosrecomp', 'thirdparty', 'dxc-bin')
DEFAULT_DXC = os.path.join(DXC_BIN, 'bin', 'x64', 'dxc-linux')
DEFAULT_VKD3D = '/usr/x86_64-w64-mingw32/sys-root/mingw/bin/vkd3d-compiler.exe'
ENTRIES = [('VsMain', 'vs_6_0', 'vs'), ('PsMain', 'ps_6_0', 'ps')]
RESIZE_ENTRIES = [('ColorMain', 'ps_6_0', 'color'), ('ColorMsMain', 'ps_6_0', 'color_ms'),
                  ('DepthMain', 'ps_6_0', 'depth'), ('DepthMsMain', 'ps_6_0', 'depth_ms'),
                  ('StencilMain', 'ps_6_0', 'stencil'), ('StencilMsMain', 'ps_6_0', 'stencil_ms')]


def compile_one(dxc, src, entry, profile, spirv):
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, 'out.bin')
        args = [dxc, '-T', profile, '-E', entry, '-O3', src, '-Fo', out]
        if spirv:
            args[1:1] = ['-spirv', '-fspv-target-env=vulkan1.1']
            # Vulkan clip space has +y down; flipping in the vertex shader keeps D3D's orientation, as the pack does.
            if profile.startswith('vs'):
                args[1:1] = ['-fvk-invert-y']
        env = dict(os.environ)
        # The Linux DXC signs DXIL through libdxil.so beside libdxcompiler.so.
        env['LD_LIBRARY_PATH'] = os.path.join(DXC_BIN, 'lib', 'x64')
        subprocess.run(args, check=True, env=env)
        with open(out, 'rb') as fh:
            return fh.read()


def compile_dxbc(vkd3d, src, entry, profile):
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, 'out.bin')
        profile = profile.replace('_6_0', '_5_1')
        env = dict(os.environ, WINEDEBUG='-all')
        subprocess.run(['wine', vkd3d, '-p', profile, '-e', entry, '-b', 'dxbc-tpf', '-o', out, src],
                       check=True, env=env, timeout=120)
        with open(out, 'rb') as fh:
            return fh.read()


def emit(name, blob):
    rows = [', '.join('0x%02x' % b for b in blob[i:i + 16]) for i in range(0, len(blob), 16)]
    return 'inline constexpr uint8_t %s[] = {\n  %s,\n};\n' % (name, ',\n  '.join(rows))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--dxc', default=DEFAULT_DXC)
    ap.add_argument('--vkd3d', default=DEFAULT_VKD3D)
    a = ap.parse_args()
    for file in sorted(os.listdir(SHADERS)):
        if not file.endswith('.hlsl'):
            continue
        stem = file[:-5]
        src = os.path.join(SHADERS, file)
        parts = ['// Generated by tools/gpu/compile_shaders.py from %s; do not edit.\n#pragma once\n\n'
                 '#include <cstdint>\n\n#include "render/shaders/host_shader_code.h"\n\n'
                 'namespace onevs100::render::shaders {\n' % file]
        hosts = []
        for entry, profile, tag in (RESIZE_ENTRIES if stem == 'resize' else ENTRIES):
            name = 'k%s_%s' % (stem.capitalize(), tag)
            parts.append(emit(name + '_dxil', compile_one(a.dxc, src, entry, profile, False)))
            parts.append(emit(name + '_dxbc', compile_dxbc(a.vkd3d, src, entry, profile)))
            parts.append(emit(name + '_spirv', compile_one(a.dxc, src, entry, profile, True)))
            hosts.append(name)
        parts.append(''.join('inline constexpr HostShaderCode %s{%s_dxil, %s_dxbc, %s_spirv};\n' % (n, n, n, n)
                             for n in hosts))
        parts.append('}  // namespace onevs100::render::shaders\n')
        with open(os.path.join(SHADERS, stem + '_shaders.h'), 'w', newline='\n') as fh:
            fh.write('\n'.join(parts))
        print('wrote ' + stem + '_shaders.h')
    return 0


if __name__ == '__main__':
    sys.exit(main())
